"""Query OSV for every resolved Maven coordinate, including test transitives.

No credentials are sent. Fail closed on network/API errors or any advisory result.
Input is generated by Maven dependency:tree -DoutputType=json.
"""
import json
import pathlib
import sys
import urllib.request

root = pathlib.Path(__file__).resolve().parents[1]
tree = json.loads((root / "target/dependency-tree.json").read_text(encoding="utf-8"))
coordinates = set()

def collect(node):
    for child in node.get("children", []):
        coordinates.add((child["groupId"] + ":" + child["artifactId"], child["version"]))
        collect(child)

collect(tree)
packages = sorted(coordinates)
findings = []
for offset in range(0, len(packages), 100):
    batch = packages[offset:offset + 100]
    query = {"queries": [{"package": {"ecosystem": "Maven", "name": name}, "version": version} for name, version in batch]}
    request = urllib.request.Request("https://api.osv.dev/v1/querybatch", json.dumps(query).encode(), {"Content-Type": "application/json"})
    with urllib.request.urlopen(request, timeout=45) as response:
        results = json.load(response)["results"]
    if len(results) != len(batch):
        raise RuntimeError("Incomplete vulnerability results")
    for (name, version), result in zip(batch, results):
        for advisory in result.get("vulns", []):
            findings.append({"package": name, "version": version, "advisory": advisory["id"]})
report = {"source": "https://osv.dev", "coordinates": len(packages), "findings": findings}
destination = root / "target/evidence/dependency-audit.json"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
for finding in findings:
    print(f"dependency finding {finding['package']}@{finding['version']} {finding['advisory']}")
print(f"DEPENDENCY_AUDIT coordinates={len(packages)} advisories={len(findings)}")
sys.exit(bool(findings))
